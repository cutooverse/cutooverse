export function setLang(l) { lang = S[l] ? l : "en"; }
export function getLang() { return lang; }
export function num(n) { return lang === "fa" ? Number(n).toLocaleString("fa-IR") : Number(n).toLocaleString("en-US"); }
export function t(key, vars = {}) {
  let s = S[lang][key] ?? S.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, typeof v === "number" ? num(v) : v);
  return s;
}
